  assert.match(drawer,/\.rundeckWorkspaceClose'\)\?\.focus\(\{\s*preventScroll:\s*true\s*\}\)/)
  assert.match(geometry,/\.is-evidence,\.is-availability,\.is-issues,\.is-unified-app,\.is-wide/)
